-- IBAN hesap numarası üretimi için sıra
CREATE SEQUENCE account_number_seq START WITH 1000 INCREMENT BY 1;

CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(150) NOT NULL,
    email      VARCHAR(200) NOT NULL UNIQUE,
    phone      VARCHAR(30),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CUSTOMER', 'TELLER', 'ADMIN')),
    customer_id   BIGINT REFERENCES customer (id),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- kind = SYSTEM: bankanın kasa hesabı (para yatırma/çekme karşı tarafı), eksiye düşebilir.
-- Tüm hesap bakiyelerinin toplamı (SYSTEM dahil) her zaman 0'dır.
CREATE TABLE account (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iban        VARCHAR(34)   NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES customer (id),
    kind        VARCHAR(10)   NOT NULL CHECK (kind IN ('CUSTOMER', 'SYSTEM')),
    currency    VARCHAR(3)    NOT NULL CHECK (currency IN ('TRY', 'USD', 'EUR')),
    balance     NUMERIC(19, 4) NOT NULL DEFAULT 0,
    status      VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLOSED')),
    version     BIGINT        NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_account_balance CHECK (kind = 'SYSTEM' OR balance >= 0),
    CONSTRAINT chk_account_owner CHECK (kind = 'SYSTEM' OR customer_id IS NOT NULL)
);
CREATE INDEX idx_account_customer ON account (customer_id);

CREATE TABLE transfer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(100)   NOT NULL UNIQUE,
    from_account_id BIGINT         NOT NULL REFERENCES account (id),
    to_account_id   BIGINT         NOT NULL REFERENCES account (id),
    amount          NUMERIC(19, 4) NOT NULL CHECK (amount > 0),
    currency        VARCHAR(3)     NOT NULL,
    type            VARCHAR(20)    NOT NULL CHECK (type IN ('EFT', 'BILL_PAYMENT', 'CARD_PAYMENT', 'DEPOSIT', 'WITHDRAWAL')),
    status          VARCHAR(10)    NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    description     VARCHAR(255),
    failure_reason  VARCHAR(255),
    initiated_by    VARCHAR(200)   NOT NULL,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    completed_at    TIMESTAMPTZ,
    CONSTRAINT chk_transfer_accounts CHECK (from_account_id <> to_account_id)
);
CREATE INDEX idx_transfer_from ON transfer (from_account_id);
CREATE INDEX idx_transfer_to ON transfer (to_account_id);

CREATE TABLE ledger_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT         NOT NULL REFERENCES account (id),
    transfer_id   BIGINT         NOT NULL REFERENCES transfer (id),
    entry_type    VARCHAR(6)     NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount        NUMERIC(19, 4) NOT NULL CHECK (amount > 0),
    balance_after NUMERIC(19, 4) NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_ledger_account ON ledger_entry (account_id, id DESC);
CREATE INDEX idx_ledger_transfer ON ledger_entry (transfer_id);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       VARCHAR(200) NOT NULL,
    action      VARCHAR(60)  NOT NULL,
    entity_type VARCHAR(40),
    entity_id   VARCHAR(60),
    details     TEXT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_created ON audit_log (id DESC);
