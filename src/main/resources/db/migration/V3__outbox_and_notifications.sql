-- Transactional outbox: event, para hareketiyle AYNI transaction'da buraya yazılır.
-- Ayrı bir publisher bu tablodan okuyup Kafka'ya gönderir (at-least-once).
CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    seq            BIGINT       GENERATED ALWAYS AS IDENTITY,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(60)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    payload        TEXT         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500)
);
CREATE UNIQUE INDEX uq_outbox_seq ON outbox_event (seq);
-- Publisher sadece yayınlanmamış satırlara bakar; kısmi index bu sorguyu küçük tutar.
CREATE INDEX idx_outbox_unpublished ON outbox_event (seq) WHERE published_at IS NULL;
CREATE INDEX idx_outbox_aggregate ON outbox_event (aggregate_type, aggregate_id);

-- Idempotent consumer: bir event'i bir consumer'ın işlediğinin kaydı.
-- (consumer, event_id) birincil anahtarı, aynı event'in ikinci kez işlenmesini DB seviyesinde engeller.
CREATE TABLE processed_event (
    consumer     VARCHAR(60) NOT NULL,
    event_id     UUID        NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (consumer, event_id)
);

-- Bildirim servisinin çıktısı (e-posta gönderimi simüle edilir).
-- customer_id'ye bilerek FK konmadı: Faz 3'te bu servis ayrı bir veritabanına taşınacak.
CREATE TABLE notification (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    UUID         NOT NULL,
    customer_id BIGINT       NOT NULL,
    transfer_id BIGINT       NOT NULL,
    channel     VARCHAR(10)  NOT NULL DEFAULT 'EMAIL',
    subject     VARCHAR(200) NOT NULL,
    message     VARCHAR(500) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_notification_event_customer UNIQUE (event_id, customer_id)
);
CREATE INDEX idx_notification_customer ON notification (customer_id, id DESC);
CREATE INDEX idx_notification_transfer ON notification (transfer_id);
