-- transfer-service veritabanı (transferdb). Hesap tablosu YOK: hesaplara sadece id ile referans verilir,
-- bütünlüğü account-service korur (servisler arası FK olmaz).
CREATE TABLE transfer (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key  VARCHAR(100)   NOT NULL UNIQUE,
    from_account_id  BIGINT         NOT NULL,
    to_account_id    BIGINT         NOT NULL,
    amount           NUMERIC(19, 4) NOT NULL CHECK (amount > 0),
    currency         VARCHAR(3)     NOT NULL,
    type             VARCHAR(20)    NOT NULL CHECK (type IN ('EFT', 'BILL_PAYMENT', 'CARD_PAYMENT', 'DEPOSIT', 'WITHDRAWAL')),
    saga_state       VARCHAR(20)    NOT NULL CHECK (saga_state IN ('STARTED', 'DEBITED', 'COMPENSATING', 'COMPLETED', 'FAILED', 'COMPENSATED')),
    failure_code     VARCHAR(40),
    failure_reason   VARCHAR(255),
    initiated_by     VARCHAR(200)   NOT NULL,
    owner_customer_id BIGINT,
    from_customer_id BIGINT,
    to_customer_id   BIGINT,
    description      VARCHAR(255),
    attempts         INT            NOT NULL DEFAULT 0,
    last_step_at     TIMESTAMPTZ    NOT NULL,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    completed_at     TIMESTAMPTZ,
    CONSTRAINT chk_transfer_accounts CHECK (from_account_id <> to_account_id)
);
-- Recovery job sadece bitmemiş saga'lara bakar.
CREATE INDEX idx_transfer_in_flight ON transfer (last_step_at)
    WHERE saga_state IN ('STARTED', 'DEBITED', 'COMPENSATING');
CREATE INDEX idx_transfer_owner ON transfer (owner_customer_id);

CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    seq            BIGINT       GENERATED ALWAYS AS IDENTITY,
    topic          VARCHAR(100) NOT NULL,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(60)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    payload        TEXT         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500)
);
CREATE UNIQUE INDEX uq_outbox_seq ON outbox_event (seq);
CREATE INDEX idx_outbox_unpublished ON outbox_event (seq) WHERE published_at IS NULL;
CREATE INDEX idx_outbox_aggregate ON outbox_event (aggregate_type, aggregate_id);
