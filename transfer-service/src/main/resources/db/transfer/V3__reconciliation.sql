-- Mutabakat: terminal transferlerin account-service işlem kayıtlarıyla karşılaştırıldığı an ve bulunan tutarsızlıklar.
ALTER TABLE transfer ADD COLUMN reconciled_at TIMESTAMPTZ;
CREATE INDEX idx_transfer_unreconciled ON transfer (id)
    WHERE reconciled_at IS NULL AND saga_state IN ('COMPLETED', 'FAILED', 'COMPENSATED');

CREATE TABLE reconciliation_finding (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT       NOT NULL,
    kind        VARCHAR(40)  NOT NULL,
    details     VARCHAR(500) NOT NULL,
    found_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);
CREATE INDEX idx_finding_open ON reconciliation_finding (id DESC) WHERE resolved_at IS NULL;
