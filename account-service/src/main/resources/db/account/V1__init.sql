-- account-service veritabanı (accountdb). Başka servis bu tablolara doğrudan erişmez.
CREATE SEQUENCE account_number_seq START WITH 1000 INCREMENT BY 1;

CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(150) NOT NULL,
    email      VARCHAR(200) NOT NULL UNIQUE,
    phone      VARCHAR(30),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CUSTOMER', 'TELLER', 'ADMIN')),
    customer_id   BIGINT REFERENCES customer (id),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- kind: CUSTOMER müşteri hesabı; CASH kasa (eksiye düşebilir); CLEARING saga sırasında yoldaki para.
-- Tüm bakiyelerin toplamı (kasa + clearing dahil) her commit'te 0'dır.
CREATE TABLE account (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iban        VARCHAR(34)    NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES customer (id),
    kind        VARCHAR(10)    NOT NULL CHECK (kind IN ('CUSTOMER', 'CASH', 'CLEARING')),
    currency    VARCHAR(3)     NOT NULL CHECK (currency IN ('TRY', 'USD', 'EUR')),
    balance     NUMERIC(19, 4) NOT NULL DEFAULT 0,
    status      VARCHAR(10)    NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLOSED')),
    version     BIGINT         NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT chk_account_balance CHECK (kind = 'CASH' OR balance >= 0),
    CONSTRAINT chk_account_owner CHECK (kind <> 'CUSTOMER' OR customer_id IS NOT NULL)
);
CREATE INDEX idx_account_customer ON account (customer_id);

CREATE TABLE ledger_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT         NOT NULL REFERENCES account (id),
    reference     VARCHAR(80)    NOT NULL,
    entry_type    VARCHAR(6)     NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount        NUMERIC(19, 4) NOT NULL CHECK (amount > 0),
    balance_after NUMERIC(19, 4) NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_ledger_account ON ledger_entry (account_id, id DESC);
CREATE INDEX idx_ledger_reference ON ledger_entry (reference);

-- İşlenmiş saga komutları (idempotency). op_key = "transferId:ADIM".
CREATE TABLE operation_log (
    op_key      VARCHAR(80) PRIMARY KEY,
    success     BOOLEAN     NOT NULL,
    reason_code VARCHAR(40),
    reason      VARCHAR(255),
    customer_id BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       VARCHAR(200) NOT NULL,
    action      VARCHAR(60)  NOT NULL,
    entity_type VARCHAR(40),
    entity_id   VARCHAR(60),
    details     TEXT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_created ON audit_log (id DESC);

-- Transactional outbox: cevaplar, bakiye değişimiyle AYNI transaction'da buraya yazılır.
CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    seq            BIGINT       GENERATED ALWAYS AS IDENTITY,
    topic          VARCHAR(100) NOT NULL,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(60)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    payload        TEXT         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500)
);
CREATE UNIQUE INDEX uq_outbox_seq ON outbox_event (seq);
CREATE INDEX idx_outbox_unpublished ON outbox_event (seq) WHERE published_at IS NULL;
CREATE INDEX idx_outbox_aggregate ON outbox_event (aggregate_type, aggregate_id);
